#pragma once
// 本机命名管道 JSON API（只读查询）：外部软件读取统计数据的接口。
// 线程模型：后台线程创建管道并负责收发；数据访问必须发生在主线程（app() 仅在主线程读写），
// 因此实际取数由主线程周期调用 ApiServe() 完成（生产-消费，单请求串行）。
// 协议详见 docs/API.md。
bool ApiStart();              // 启动后台管道服务线程（失败返回 false，不影响主程序运行）
void ApiStop();               // 停止并清理（进程退出前调用）
void ApiServe();              // 主线程周期调用：若存在挂起请求则构建 JSON 响应并放行
